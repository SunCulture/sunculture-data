        jsf_date,
        jsf_completed_date,
        device_id,
        warranty_expiry_date,
        parentAccountId,
        externalId,
        createdAt,
        customerId,
        companyRegion,
        customerType,
        customerTypeId,
        customer_name,
        gender,
        town,
        gps,
        latitude,
        longitude,
        village,
        subcounty,
        County,
